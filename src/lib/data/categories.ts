export const allDatasets: DatasetItem[] = allCategories.flatMap((cat) => cat.datasets);

export const searchDatasets = (query: string): DatasetItem[] => {
  const q = query.toLowerCase().trim();
  if (!q) return allDatasets;
  return allDatasets.filter(
    (ds) =>
      ds.name.toLowerCase().includes(q) ||
      ds.description.toLowerCase().includes(q) ||
      ds.source.toLowerCase().includes(q) ||
      ds.id.toLowerCase().includes(q),
  );
};
